"""Build-time only: embed the EXISTING input schemas as data, no new protocol."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
parts = ['extends RefCounted\n# Generated by tools/schema_data.py from existing public schemas.\n']
for name, path in [('REQUEST', 'request.schema.json'), ('CONFIG', 'config.schema.json')]:
    parts.append(f'const {name} = ' + json.dumps(json.loads((root/'schemas'/path).read_text()), ensure_ascii=False, indent=2) + '\n')
target = root/'godot_candidate/addons/mapgen/schema_data.gd'
target.write_text(''.join(parts))
